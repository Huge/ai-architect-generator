# Map compact codes → (English type, Czech name)
TYPE_MAP = {
    "E":  ("Entry",      "Vstup"),
    "B":  ("Bath",       "Koupelna"),
    "T":  ("Bath",       "Toaleta"),
    "K":  ("Kitchen",    "Kuchyně"),
    "L":  ("LivingRoom", "Obývák"),
    "R":  ("Bedroom",    "Ložnice"),
    "D":  ("Dining",     "Jídelna"),
    "H":  ("Hallway",    "Chodba"),
    "O":  ("Office",     "Pracovna"),
    "S":  ("Storage",    "Sklad"),
    "C":  ("Closet",     "Šatna"),
    "P":  ("Pantry",     "Spíž"),
    "U":  ("Utility",    "Technická"),
}


def room(code: str, x1: float, y1: float, x2: float, y2: float, idx: int) -> dict:
    """Build a Kalkulio room dict from a bounding box."""
    typ, nazev = TYPE_MAP[code]
    poly = [[x1, y1], [x2, y1], [x2, y2], [x1, y2]]  # CCW
    area = round((x2 - x1) * (y2 - y1), 2)
    return {
        "id": f"P{idx}",
        "typ": typ,
        "nazev": nazev,
        "polygon": poly,
        "plocha_m2": area,
        "venkovni": False,
    }


def build_plan(rooms_spec: list[tuple]) -> dict:
    """Build a full Kalkulio plan dict from a list of (code, x1, y1, x2, y2).

    Walls and openings will be derived by post_process.
    """
    rooms = [room(code, x1, y1, x2, y2, i + 1)
             for i, (code, x1, y1, x2, y2) in enumerate(rooms_spec)]
    return {"steny": [], "otvory": [], "prostory": rooms}


