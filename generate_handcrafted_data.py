# ----- Driver --------------------------------------------------------------

def main() -> None:
    existing = sorted(OUTPUT_DIR.glob("synthetic_*.json"))
    start_idx = len(existing) + 1
    print(f"📁 Output dir: {OUTPUT_DIR}  (existing synthetic: {len(existing)})")
    print(f"📐 Generating {len(PLANS)} handcrafted plans starting at #{start_idx}\n")

    saved = 0
    failed = 0
    style_counts: dict[str, int] = {}

    for i, (target_area, style, rooms_spec) in enumerate(PLANS, 1):
        plan = build_plan(rooms_spec)
        actual_area = sum(r["plocha_m2"] for r in plan["prostory"])

        # Run through post_process to derive walls + sanity-check
        try:
            cleaned = post_process(plan, target_area=float(target_area))
        except Exception as e:
            print(f"  [{i:3d}/{len(PLANS)}] ✗ {target_area:>3d} m²  {style[:30]:30s}  post_process: {e}")
            failed += 1
            continue

        if not has_closed_exterior_loop(cleaned):
            print(f"  [{i:3d}/{len(PLANS)}] ✗ {target_area:>3d} m²  {style[:30]:30s}  NOT WATERTIGHT (raw {actual_area:.1f} m²)")
            failed += 1
            continue

        idx = start_idx + saved
        out_path = OUTPUT_DIR / f"synthetic_{idx:03d}.json"
        cleaned["metadata"] = {
            "source": "handcrafted",
            "model": "opus-4.7",
            "target_area_m2": target_area,
            "style": style,
        }
        out_path.write_text(json.dumps(cleaned, ensure_ascii=False, separators=(",", ":")))
        saved += 1
        style_counts[style] = style_counts.get(style, 0) + 1
        n_rooms = len(cleaned["prostory"])
        n_walls = len(cleaned["steny"])
        print(f"  [{i:3d}/{len(PLANS)}] ✓ {target_area:>3d} m²  {style[:30]:30s}  → {out_path.name}  ({n_rooms} rooms, {n_walls} walls)")

    print()
    print("=" * 70)
    print(f"📊 Saved {saved}/{len(PLANS)} plans ({saved/max(1,len(PLANS))*100:.1f}% success)")
    if failed:
        print(f"   {failed} plans failed validation (check designs)")
    print(f"   Total synthetic plans now: {start_idx - 1 + saved}")
    print(f"📁 Files: {OUTPUT_DIR}/synthetic_*.json")
    print()
    print("Next steps:")
    print("  1. python prepare_data.py     # rebuild train/valid jsonl")
    print("  2. python train.py            # retrain v4")


if __name__ == "__main__":
    main()
